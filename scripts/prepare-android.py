#!/usr/bin/env python3
"""Build an offline WebView bundle; leave the standalone game unchanged."""
import base64
import hashlib
import json
import pathlib
import re

root = pathlib.Path(__file__).resolve().parent.parent
source = (root / "Prototype.html").read_bytes()
html = source.decode("utf-8")
match = re.search(r"const A = (\{.*?\});", html)
if not match:
    raise SystemExit("Game asset map was not found")
assets = json.loads(match.group(1))
target = root / "www"
marker = target / ".nowell-generated"
if target.exists() and any(target.iterdir()) and not marker.exists():
    raise SystemExit("www contains non-generated files; preserve them before building")
(target / "media").mkdir(parents=True, exist_ok=True)
marker.write_text("Generated by scripts/prepare-android.py\n")
extensions = {"image/webp": "webp", "image/jpeg": "jpg", "image/png": "png", "audio/mpeg": "mp3", "video/mp4": "mp4"}
for key, value in assets.items():
    if not re.fullmatch(r"[a-zA-Z0-9_]+", key):
        raise SystemExit(f"Unsafe asset key: {key}")
    header, encoded = value.split(",", 1)
    mime = header.removeprefix("data:").split(";")[0]
    if mime not in extensions or ";base64" not in header:
        raise SystemExit(f"Unsupported embedded resource: {key}")
    name = f"media/{key}.{extensions[mime]}"
    (target / name).write_bytes(base64.b64decode(encoded, validate=True))
    assets[key] = name
html = html[:match.start(1)] + json.dumps(assets, ensure_ascii=False, separators=(",", ":")) + html[match.end(1):]
html = html.replace("<script>\n(() =>", '<script src="cordova.js"></script>\n<script>\n(() =>', 1)
(target / "index.html").write_text(html, encoding="utf-8")
(target / "build-info.json").write_text(json.dumps({"version": "0.1.2", "source_sha256": hashlib.sha256(source).hexdigest(), "asset_count": len(assets)}, indent=2) + "\n")
print(f"Prepared {len(assets)} offline resources; HTML {len(html.encode('utf-8')):,} bytes")
